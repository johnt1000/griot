"""The hooks refuse a commit message that credits an AI assistant.

The author of a commit in this project is the person who makes it: no
assistant as co-author, no session link, no "Generated with". That was a
rule kept by review alone, and review is exactly what a commit made in a
hurry skips. `commit-msg` refuses such a line in the message being written,
and `pre-push` in the messages of the commits a push would send, which also
covers a cherry-pick or a rebase that runs no commit hook.

Naming an assistant is fine otherwise: griot supports Claude Code, and a
commit says so. What is refused is a line that credits one.

Run for real, in throwaway repositories, as tests/test_git_hooks.py does.
"""

