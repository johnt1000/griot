@pytest.fixture
def repo(tmp_path):
    """No sensitive-terms.txt on purpose: the rule does not depend on it."""
    return make_repo(tmp_path / "repo", write_script(tmp_path / "gitleaks-stub", "exit 0\n"))


@pytest.fixture
def remote(repo, tmp_path):
    path = tmp_path / "remote.git"
    assert _git(tmp_path, "init", "-q", "--bare", "-b", "main", str(path), env=repo.env).returncode == 0
    assert _git(repo, "remote", "add", "origin", str(path), env=repo.env).returncode == 0
    _commit(repo, "first")
    return path


def _commit(repo, message, hooks=True, name="notes.md"):
    (repo / name).write_text(message + "\n")
    assert _git(repo, "add", name, env=repo.env).returncode == 0
    return _git(repo, "commit", "-q", "-m", message, *([] if hooks else ["--no-verify"]), env=repo.env)


def _count(repo):
    done = _git(repo, "rev-list", "--count", "HEAD", env=repo.env)
    return int(done.stdout.strip()) if done.returncode == 0 else 0


# --- commit-msg -------------------------------------------------------------------------------------


@pytest.mark.parametrize("line", CREDITS)
def test_a_message_that_credits_an_assistant_is_refused(repo, line):
    done = _commit(repo, f"fix: something\n\n{line}")

    assert done.returncode != 0 and "attribution" in done.stderr
    assert _count(repo) == 0


@pytest.mark.parametrize("line", FINE)
def test_a_message_that_only_names_one_or_credits_a_person_goes_through(repo, line):
    done = _commit(repo, f"{line}\n\nbody")

    assert done.returncode == 0, done.stderr


def test_a_template_comment_in_an_editor_is_not_read(repo, tmp_path):
    """git takes its own comment lines out of a message written in an
    editor: a credit there never reaches the commit."""
    message = tmp_path / "MSG"
    message.write_text(f"docs: fine\n# {CREDITS[0]}\n")

    done = subprocess.run([str(HOOKS / "commit-msg"), str(message)], capture_output=True, text=True, cwd=repo,
                          env={**repo.env, "GIT_EDITOR": "vi"})

    assert done.returncode == 0, done.stderr


def test_a_credit_on_a_comment_line_given_with_m_is_refused(repo):
    """With -m there is no template, and git keeps a line that starts with #."""
    done = _commit(repo, f"fix: something\n\n# {CREDITS[0]}")

    assert done.returncode != 0 and "attribution" in done.stderr


# --- pre-push ---------------------------------------------------------------------------------------


def test_a_commit_that_credits_an_assistant_is_not_pushed(repo, remote):
    assert _commit(repo, f"fix: something\n\n{CREDITS[0]}", hooks=False).returncode == 0
    head = _git(repo, "rev-parse", "--short", "HEAD", env=repo.env).stdout.strip()

    done = _git(repo, "push", "-q", "origin", "main", env=repo.env)

    assert done.returncode != 0 and "attribution" in done.stderr and head in done.stderr
    assert _git(repo, "--git-dir", str(remote), "rev-parse", "-q", "--verify", "main", env=repo.env).returncode != 0


def test_a_push_of_clean_commits_goes_through(repo, remote):
    assert _commit(repo, FINE[1], name="more.md").returncode == 0

    done = _git(repo, "push", "-q", "origin", "main", env=repo.env)

    assert done.returncode == 0, done.stderr


QUOTING_A_CREDIT = """build(deps): bump setup-uv from 10.2.0 to 10.3.0

<blockquote>
<li>Generated with Copilot by upstream</li>
</blockquote>
> https://claude.ai/code/session_0123456789"""


def test_a_commit_that_quotes_a_credit_is_pushed(repo, remote):
    """pre-push reads messages through git's own regex: a quote has to pass
    there too, not only in grep."""
    assert _commit(repo, QUOTING_A_CREDIT, hooks=False, name="more.md").returncode == 0

    done = _git(repo, "push", "-q", "origin", "main", env=repo.env)

    assert done.returncode == 0, done.stderr


@pytest.mark.parametrize("hooks", [True, False], ids=["commit-msg", "pre-push"])
def test_a_quote_on_one_line_does_not_cover_a_credit_on_the_next(repo, remote, hooks):
    """`<` or `>` exempts what follows it on its own line only: a quote
    earlier in the message does not stretch over a credit below it."""
    message = f"fix: the <details> block\n\n> quoted\n{CREDITS[6]}"
    if hooks:
        done = _commit(repo, message, name="more.md")
    else:
        assert _commit(repo, message, hooks=False, name="more.md").returncode == 0
        done = _git(repo, "push", "-q", "origin", "main", env=repo.env)

    assert done.returncode != 0 and "attribution" in done.stderr


def test_the_rule_holds_with_a_terms_list_too(repo):
    (repo / ".git" / "sensitive-terms.txt").write_text("acme-private\n")

    done = _commit(repo, f"fix: something\n\n{CREDITS[0]}")

    assert done.returncode != 0 and "attribution" in done.stderr


def test_an_annotated_tag_that_credits_an_assistant_is_not_pushed(repo, remote):
    assert _git(repo, "tag", "-a", "v1", "-m", f"release\n\n{CREDITS[0]}", env=repo.env).returncode == 0

    done = _git(repo, "push", "-q", "origin", "main", "v1", env=repo.env)

    assert done.returncode != 0 and "attribution" in done.stderr and "v1" in done.stderr
